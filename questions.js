function lowerFirst(s) {
  return s ? s.charAt(0).toLowerCase() + s.slice(1) : s;
}

function shuffle(arr) {
  const a = [...arr];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// Build a variant of a core question: reworded prompt, shuffled options,
// correct answer letter updated to match new position.
function makeVariant(core, domain, variantIndex) {
  const template = VARIANT_TEMPLATES[variantIndex % VARIANT_TEMPLATES.length];
  const decoys = DECOY_POOLS[domain] || [];

  const correctText = core.options["ABCDE".indexOf(core.answer)];

  // Start with the correct answer + a shuffled mix of core distractors and pool decoys
  const otherCoreOptions = core.options.filter(o => o !== correctText);
  const pool = shuffle(decoys).slice(0, 2);
  const candidates = shuffle([correctText, ...otherCoreOptions.slice(0, 2), ...pool]).slice(0, 4);

  // Ensure the correct answer is present exactly once
  if (!candidates.includes(correctText)) candidates[0] = correctText;

  const newOptions = shuffle(candidates);
  const newAnswer = "ABCD"[newOptions.indexOf(correctText)];

  return {
    q: template(core.q),
    options: newOptions,
    answer: newAnswer,
    _variantOf: core.q // for debugging / dedup
  };
}

// ============================================================================
// ASSEMBLE FINAL QUESTION BANK
// Target: at least 12 * 60 = 720 total questions.
// Distribution target: same as DOMAIN_WEIGHTS per bundle.
// We generate variants until each domain has enough unique entries that
// 12 bundles * per-bundle count can be filled with non-overlapping questions.
// ============================================================================

const VARIANTS_PER_CORE = 12; // each core question can spawn many variants

function buildBank() {
  const bank = [];
  let id = 1;

  for (const [domain, cores] of Object.entries(CORE)) {
    // Push the core questions
    for (const c of cores) {
      bank.push({
        id: id++,
        domain,
        q: c.q,
        options: c.options,
        answer: c.answer
      });
    }

    // Push generated variants
    for (let v = 0; v < VARIANTS_PER_CORE; v++) {
      for (const c of cores) {
        bank.push({
          id: id++,
          domain,
          ...makeVariant(c, domain, v)
        });
      }
    }
  }

  return bank;
}

